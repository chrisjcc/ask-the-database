"""Multi-Turn Action Token Loss Masking for Relational Tool-Use Agents.

Isolates policy-generated thought and action tokens while strictly zeroing
environment observation tokens (SQLite sandbox execution results, schema dumps)
to prevent policy gradient leakage and reward hacking.
"""

from __future__ import annotations

import logging
import re
from typing import Any

import torch

logger = logging.getLogger(__name__)

# Delimiter tags for agent actions and environment observations
ACTION_TAGS = [
    (r"<thought>", r"</thought>"),
    (r"<tool_call>", r"</tool_call>"),
    (r'<tool\s+name=["\']?[^"\'>\s]+["\']?\s*>', r"</tool>"),
    (r"<final_answer>", r"</final_answer>"),
]

OBSERVATION_TAGS = [
    (r"<tool_response>", r"</tool_response>"),
    (r"<observation>", r"</observation>"),
]

CHATML_ASSISTANT_START = "<|im_start|>assistant"
CHATML_END = "<|im_end|>"
CHATML_TOOL_START = "<|im_start|>tool"


class ActionMaskGenerator:
    """Generates token-level action loss masks for multi-turn interactive trajectories.

    Strict Invariant:
        M_t = 1 for tokens inside agent thought traces, tool calls, and final answers.
        M_t = 0 for tokens in system prompts, user queries, and environment observations.
    """

    def __init__(
        self,
        tokenizer: Any | None = None,
        include_action_tags: bool = True,
    ) -> None:
        """Initialize the ActionMaskGenerator.

        Args:
            tokenizer: Hugging Face PreTrainedTokenizer or compatible tokenizer.
            include_action_tags: If True, delimiter tags generated by the agent
                (e.g. <tool_call>, </tool_call>) are included in the active loss mask.
        """
        self.tokenizer = tokenizer
        self.include_action_tags = include_action_tags

    def generate_from_messages(
        self,
        messages: list[dict[str, str]],
        tokenizer: Any | None = None,
        max_length: int | None = None,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        """Generate input_ids and action_mask directly from structured ChatML messages.

        Args:
            messages: List of message dictionaries, e.g.
                [{"role": "system", "content": "..."},
                 {"role": "user", "content": "..."},
                 {"role": "assistant", "content": "<thought>...</thought><tool...>...</tool>"},
                 {"role": "tool", "content": "Query execution result..."}]
            tokenizer: Tokenizer override.
            max_length: Optional sequence truncation limit.

        Returns:
            tuple[torch.Tensor, torch.Tensor]: (input_ids, action_mask) of shape (1, L).
        """
        tok = tokenizer or self.tokenizer
        if tok is None:
            raise ValueError("Tokenizer must be provided to tokenize messages.")

        all_input_ids: list[int] = []
        all_mask: list[float] = []

        for msg in messages:
            role = msg["role"]
            content = msg["content"]

            # Construct ChatML block for the turn
            turn_text = f"<|im_start|>{role}\n{content}<|im_end|>\n"
            turn_ids = tok.encode(turn_text, add_special_tokens=False)

            # Policy generates assistant turns (mask=1.0); system/user/tool turns are observations (mask=0.0)
            turn_mask = [1.0] * len(turn_ids) if role == "assistant" else [0.0] * len(turn_ids)

            all_input_ids.extend(turn_ids)
            all_mask.extend(turn_mask)

        if max_length and len(all_input_ids) > max_length:
            all_input_ids = all_input_ids[:max_length]
            all_mask = all_mask[:max_length]

        input_ids_t = torch.tensor([all_input_ids], dtype=torch.long)
        action_mask_t = torch.tensor([all_mask], dtype=torch.float32)
        return input_ids_t, action_mask_t

    def generate_from_text(
        self,
        text: str,
        tokenizer: Any | None = None,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        """Generate token-level action mask by scanning text for delimiter spans.

        Args:
            text: Full multi-turn trajectory string containing delimiter tags or ChatML tokens.
            tokenizer: Tokenizer override.

        Returns:
            tuple[torch.Tensor, torch.Tensor]: (input_ids, action_mask) of shape (1, L).
        """
        tok = tokenizer or self.tokenizer
        if tok is None:
            raise ValueError("Tokenizer must be provided to generate action mask from text.")

        encoding = tok(text, return_offsets_mapping=True, add_special_tokens=False)
        input_ids = encoding["input_ids"]
        offset_mapping = encoding.get("offset_mapping", None)

        # 1. Identify active (assistant / action) character intervals
        active_intervals = self._find_active_char_intervals(text)

        # 2. Map character intervals to token-level binary mask
        if offset_mapping is not None and len(offset_mapping) == len(input_ids):
            mask = [0.0] * len(input_ids)
            for idx, (start_char, end_char) in enumerate(offset_mapping):
                if start_char == end_char:
                    continue
                # Token is active if its midpoint falls inside any active interval
                mid = (start_char + end_char) / 2.0
                if any(start <= mid <= end for start, end in active_intervals):
                    mask[idx] = 1.0
        else:
            # Fallback: substring scanning over decoded tokens
            mask = self._generate_mask_from_token_ids(input_ids, tok)

        input_ids_t = torch.tensor([input_ids], dtype=torch.long)
        action_mask_t = torch.tensor([mask], dtype=torch.float32)
        return input_ids_t, action_mask_t

    def generate_from_tokens(
        self,
        input_ids: torch.Tensor,
        tokenizer: Any | None = None,
    ) -> torch.Tensor:
        """Generate action mask given an existing token ID tensor.

        Args:
            input_ids: Tensor of shape (B, L) or (L,).
            tokenizer: Tokenizer override.

        Returns:
            torch.Tensor: Action mask of identical shape with float values in {0.0, 1.0}.
        """
        tok = tokenizer or self.tokenizer
        if tok is None:
            raise ValueError("Tokenizer must be provided to decode token IDs.")

        orig_dim = input_ids.dim()
        batch_ids = input_ids.unsqueeze(0) if orig_dim == 1 else input_ids

        batch_masks: list[torch.Tensor] = []
        for row in batch_ids:
            # Decode full row and map tokens
            token_list = row.tolist()
            mask_list = self._generate_mask_from_token_ids(token_list, tok)
            batch_masks.append(
                torch.tensor(mask_list, dtype=torch.float32, device=input_ids.device)
            )

        result = torch.stack(batch_masks, dim=0)
        return result.squeeze(0) if orig_dim == 1 else result

    def _find_active_char_intervals(self, text: str) -> list[tuple[int, int]]:
        """Identify [start, end] character spans that represent agent actions."""
        active_intervals: list[tuple[int, int]] = []

        # 1. ChatML assistant turns: <|im_start|>assistant ... <|im_end|>
        chatml_pattern = re.compile(
            rf"{re.escape(CHATML_ASSISTANT_START)}(.*?)(?:{re.escape(CHATML_END)}|$)",
            re.DOTALL,
        )
        for m in chatml_pattern.finditer(text):
            if self.include_action_tags:
                active_intervals.append((m.start(), m.end()))
            else:
                active_intervals.append((m.start(1), m.end(1)))

        # 2. Tagged action blocks: <thought>, <tool_call>, <tool name=...>, <final_answer>
        for start_tag, end_tag in ACTION_TAGS:
            tag_pattern = re.compile(rf"({start_tag})(.*?)({end_tag})", re.DOTALL | re.IGNORECASE)
            for m in tag_pattern.finditer(text):
                if self.include_action_tags:
                    active_intervals.append((m.start(), m.end()))
                else:
                    active_intervals.append((m.start(2), m.end(2)))

        # 3. Explicitly excise observation spans: <tool_response>, <observation>, <|im_start|>tool
        obs_intervals: list[tuple[int, int]] = []
        for start_tag, end_tag in OBSERVATION_TAGS:
            obs_pattern = re.compile(rf"{start_tag}.*?{end_tag}", re.DOTALL | re.IGNORECASE)
            for m in obs_pattern.finditer(text):
                obs_intervals.append((m.start(), m.end()))

        chatml_tool_pattern = re.compile(
            rf"{re.escape(CHATML_TOOL_START)}.*?(?:{re.escape(CHATML_END)}|$)",
            re.DOTALL,
        )
        for m in chatml_tool_pattern.finditer(text):
            obs_intervals.append((m.start(), m.end()))

        # Filter active intervals: remove overlaps with observations
        clean_intervals: list[tuple[int, int]] = []
        for a_start, a_end in active_intervals:
            overlaps_obs = any(
                max(a_start, o_start) < min(a_end, o_end) for o_start, o_end in obs_intervals
            )
            if not overlaps_obs:
                clean_intervals.append((a_start, a_end))

        # Merge overlapping or contiguous intervals
        if not clean_intervals:
            return []

        clean_intervals.sort(key=lambda x: x[0])
        merged = [clean_intervals[0]]
        for start, end in clean_intervals[1:]:
            last_start, last_end = merged[-1]
            if start <= last_end:
                merged[-1] = (last_start, max(last_end, end))
            else:
                merged.append((start, end))

        return merged

    def _generate_mask_from_token_ids(
        self,
        token_ids: list[int],
        tokenizer: Any,
    ) -> list[float]:
        """State machine mask generator over decoded token chunks."""
        decoded_tokens = [tokenizer.decode([t]) for t in token_ids]
        mask = [0.0] * len(token_ids)

        in_action = False
        in_observation = False

        for i, tok_str in enumerate(decoded_tokens):
            lower_tok = tok_str.lower()

            # Check for turn/tag beginnings
            if (
                CHATML_ASSISTANT_START in tok_str
                or "<tool_call>" in lower_tok
                or "<tool " in lower_tok
                or "<thought>" in lower_tok
                or "<final_answer>" in lower_tok
            ):
                in_action = True
                in_observation = False

            if (
                CHATML_TOOL_START in tok_str
                or "<tool_response>" in lower_tok
                or "<observation>" in lower_tok
            ):
                in_action = False
                in_observation = True

            # Assign mask based on current state
            if in_action and not in_observation:
                mask[i] = 1.0
            else:
                mask[i] = 0.0

            # Check for turn/tag ends
            if (
                "</tool_call>" in lower_tok
                or "</tool>" in lower_tok
                or "</thought>" in lower_tok
                or "</final_answer>" in lower_tok
                or CHATML_END in tok_str
            ):
                in_action = False

            if (
                "</tool_response>" in lower_tok
                or "</observation>" in lower_tok
                or (in_observation and CHATML_END in tok_str)
            ):
                in_observation = False

        return mask


def assert_zero_observation_leakage(
    action_mask: torch.Tensor,
    observation_indices: list[int] | torch.Tensor,
) -> None:
    """Assert that observation token positions strictly receive zero mask."""
    if isinstance(observation_indices, list):
        obs_idx = torch.tensor(observation_indices, dtype=torch.long, device=action_mask.device)
    else:
        obs_idx = observation_indices.to(device=action_mask.device, dtype=torch.long)

    if obs_idx.numel() == 0:
        return

    flattened_mask = action_mask.view(-1)
    obs_mask_values = flattened_mask[obs_idx]

    non_zero = (obs_mask_values != 0.0).sum().item()
    if non_zero > 0:
        raise AssertionError(
            f"Observation leakage detected! {non_zero} observation tokens received non-zero mask: "
            f"{obs_mask_values[obs_mask_values != 0.0]}"
        )
